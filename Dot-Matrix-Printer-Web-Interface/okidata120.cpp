size_t okidata_translate(uint8_t* data, size_t length, uint8_t* out_buffer, size_t out_buffer_len)
{
  if (length == 0 || out_buffer_len < 2) return 0;

  bool cursorDown = false;
  uint8_t* start = out_buffer;

  // Send reset char to reset cursor mode (to keep a know state for our simplicity)
  *(out_buffer++) = CMD_CANCEL;
  out_buffer_len--;

  for (size_t i = 0; i < length; i++)
  {
    uint8_t c;
    if (cursorDown)
      c = CURSOR_DOWN_LOOKUP[data[i]];
    else
      c = CURSOR_UP_LOOKUP[data[i]];

    if (c == 0)
    {
      // Character was zero, meaning it was not found in the current charset
      // Try and find the character in the other charset
      if (cursorDown)
        c = CURSOR_UP_LOOKUP[data[i]];
      else
        c = CURSOR_DOWN_LOOKUP[data[i]];

      if (c == 0)
      {
        // Character doesn't exist at all, just print a space instead
        c = ' ';
      } else {
        // We need to switch charsets to print this char, ensure there's enough room for both characters
        if (out_buffer_len < 2) return (size_t)(out_buffer - start);
        *(out_buffer++) = (cursorDown ? CMD_CURSOR_UP : CMD_CURSOR_DOWN);
        out_buffer_len--;
        cursorDown = !cursorDown;
      }
    }

    // Save character to buffer, possibly after switching cursor mode
    *(out_buffer++) = c;
    out_buffer_len--;
    if (out_buffer_len == 0) return (size_t)(out_buffer - start);
  }

  return (size_t)(out_buffer - start);
}


